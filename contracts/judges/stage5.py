"""
stage5.py —— 逐章写作与全书验收那一层的判据行。源是 `docs/schema/stage5.md` §六（**唯一落点**）。

**48 条现役：8 HARD · 26 INFO · 9 度量 · 5 查不了。**

【一张表，两相共用】落盘闸门 / `--recheck` / `--revalidate` / `--apply-edit` /
全书验收相**读同一张表**，谁也不许再抄一份。原型此前把书级那 8 条住在
`n7_review.RULES6` 里、靠一个 `_merged_rules()` 合起来，而
`stage5_common` 得反向 lazy-import 才拿得到——**一张表拆成两半的全部成本都在那个环上**。

【判据 id 一律照抄文档，不加 stage 前缀】它们是与 `wontfix.json` 的键、
与 `_provenance.fixes` 的引用之间的契约——加个前缀就等于把存量豁免全部作废。

【落点账已经平过】F4-0 审计：原型那 43 条里 **20 条在需求文档里根本没有落点**，
另有 4 条指着收不了它们的地方（`Q-9` / `Q-1` / 裸 `R-3` / 一行写着「无守卫」的 `R-7.5`）。
已在 `docs/BACKEND_CONTRACT.md` 补 17 行、拆 1 行，并把 `R-8` 一整节九行逐行重判
（那一节说的是**机制**，不是对某份产物的判定）。⇒ 每一条的 `requirement` 都是核过的。

【本层特有的三条，与前四层都不同】

**① 这是第一个 `repair != 'NONE'` 的层。** 23 条 `actionable`：13 条 `UNIQUE` + 10 条 `FREE`。
判准是**满足这条判据的路径唯一吗**——不是「能不能靠重写修」（那是 `actionable`）。
原型实测代价：可反哺条目 **36 → 9（转人工 27 条，75%）**，其中一本是 **10 → 0**。
⚠ **落进 `FREE` 不等于不管**：它照常出现在报告与界面上，只是不进反哺 prompt，
改由人看一眼再决定（`--apply-edit` 0 成本改，或人工点重写）。

**② 这是第一个要填 `directive` 的层。** 那句话会被 `--revise` 发回写手，
而 `_provenance.fixes` 只存 `[[rule, evidence_key]]` **引用**——指令由本表生成，
存第二份就会跟着表漂。⚠ `bool(directive) == (repair != 'NONE')` 由注册期双向钉住。

**③ `actionable` 在本层回到它的本义。** stage6/stage7 把它读成「人能 0 成本改掉」
（那是一次登记在案的语义裁决，`docs/schema/_report.md` §2.1），而本层是**原义**：
「值不值得花一次钱让写手重写」。`contracts/schema/report.py::finding` 从
`repair != 'NONE'` 派生它，两种读法在这里终于合流。

⚠ **徽章结构上永远不可能是 `pass`**：本表有 **5 条 `unver`**，其中 `must_hold_unver`
每本都产（全书 27 条按定义查不了文面）⇒ 最好情况是 `amber`（`passed=True`、退出码 0）。
这不是缺陷，是本层「能查的都查了，查不了的写在脸上」的可见形态。**与 stage4 相反**
（那一层没有一条 `unver`，徽章可以是真绿）。
"""
from __future__ import annotations

from contracts.rules import REGISTRY, Rule

STAGE = 'stage5'


def _hard(rule: str, item: str, requirement: str, *, owner: str = STAGE, **kw) -> Rule:
    return REGISTRY.register(Rule(rule=rule, stage=STAGE, item=item, sev='hard',
                                  who_checks='HARD', requirement=requirement,
                                  owner=owner, **kw))


def _info(rule: str, item: str, requirement: str, *, owner: str = STAGE, **kw) -> Rule:
    return REGISTRY.register(Rule(rule=rule, stage=STAGE, item=item, sev='info',
                                  who_checks='INFO', requirement=requirement,
                                  owner=owner, **kw))


def _metric(rule: str, item: str, requirement: str, **kw) -> Rule:
    """度量：**无条件报出**，`owner=None`（它不是一条结论，没有「根因第一嫌疑层」）。"""
    return REGISTRY.register(Rule(rule=rule, stage=STAGE, item=item, sev='metric',
                                  who_checks='METRIC', requirement=requirement, **kw))


def _unver(rule: str, item: str, requirement: str, *, who_checks: str = 'INFO', **kw) -> Rule:
    """查不了的：**永远输出**，不是「还没写完」。

    ⚠ 本层 5 条里 4 条是 `INFO`（**判定前提不成立时出声**：这一章没有成稿 / 两条臂
    各有一份 / 这本书没有可查的秘密 / 这一拍提不出可回查的原子），
    只有 `must_hold_unver` 是 `HUMAN`——那一组按定义就该人判（`R-7.11` 那一格标着 `人`）。
    合成一个默认值，其中一族就会指着一个说着别的话的需求行。
    """
    return REGISTRY.register(Rule(rule=rule, stage=STAGE, item=item, sev='unver',
                                  who_checks=who_checks,          # type: ignore[arg-type]
                                  requirement=requirement, **kw))


